// ed_mode: РЕЖИМЫ РЕДАКТОРА как ДАННЫЕ (а не номера по файлу).
//
// Что такое режим: готовое рабочее место со своим документом и своими панелями
// («ui» — правка фронта, дальше «scene» — правка сцены). Режим ЗАВОДИТ своё
// приложение-режим (окно, цикл кадра) и объявляет себя ОДНОЙ записью.
//
// ЗАЧЕМ: было «один бинарь ui_edit, который и режим, и приложение» — второй режим
// пришлось бы вписывать правками по тому же main. Стало: хост (editor) знает
// СПИСОК режимов и выбирает по id (--mode ui), а не по номеру в коде.
//
// ГРАНИЦА (как у ed_cmd/ed_doc/ed_workspace): здесь НЕТ ни виджетов, ни GL, ни
// сцены — только записи режимов и доступ. Таблица одна (заводит вход хоста).
#pragma once

#define ED_MODE_MAX 8 // ёмкость: режимов у редактора (сейчас 1: "ui")

// Один режим: id (ключ --mode), подпись (заголовок/отчёты) и вход.
typedef struct EdMode {
    const char *id;                    // "ui"
    const char *caption;               // "UI"
    int (*run)(int argc, char **argv); // вход: режим сам ведёт окно и цикл кадра
} EdMode;

void ed_mode_add(const EdMode *m);          // завести запись (повтор id — отказ)
int ed_mode_n(void);                        // сколько режимов заведено
const EdMode *ed_mode_at(int i);            // запись по порядку (0 вне границ)
const EdMode *ed_mode_find(const char *id); // запись по id (0 — такого нет)
