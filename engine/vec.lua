-- Сцена на скриптах: та же что vec_demo, но логика здесь.
-- scene(t): секунды. Координаты 640x360, начало слева сверху.
function scene(t)
  rect(20, 20, 600, 320, 0.8, 0.8, 0.8, 1.0)
  line(20, 20, 620, 340, 1.0, 0.2, 0.2, 1.0)
  local cx = 320 + 200 * math.cos(t * 1.8)
  local cy = 180 + 100 * math.sin(t * 3.0)
  circle(cx, cy, 40, 0, 0.2, 0.6, 1.0, 1.0)
  rect(cx - 50, cy - 50, 100, 100, 1.0, 1.0, 0.0, 0.5)
  line(20, 340, 620, 20, 0.2, 1.0, 0.2, 1.0)
  circle(100, 280, 18, 0, 1.0, 0.5, 0.0, 0.8)
end
