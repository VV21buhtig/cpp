// Фаза 2: атлас глифов (stb_truetype, vendored public domain).
// ASCII 32..126, один размер (16px), R8-текстура. malloc только в init.
// Кадр: ui_text_quad() складывает квады в фикс.массив (без malloc),
// ui_text_flush() рисует своей программой поверх всего (бленд, без глубины).
#ifndef ENGINE_UI_TEXT_H
#define ENGINE_UI_TEXT_H

// Квад = ОДИН ГЛИФ (не строка!). Предел обязан вмещать ХУДШИЙ кадр редактора:
// хром (вкладки/заголовки/инспектор/палитра/дерево/подсказка) + подписи документа
// (до UI_MAX_WIDGETS=64 имён) + строки дерева с типами. 512 не вмещал: подписи
// ~70 виджетов съедали бюджет, и надписи панелей пропадали МОЛЧА (баг тестера
// «сломал отображение текста»). 4096 = предел фигур вектора (vec_upload).
#define UI_TEXT_MAXQ 4096

typedef struct UiText UiText;

UiText *ui_text_init(const char *fontPath, float px);
void ui_text_destroy(UiText *t);
// Текст влево от (x,y) — верх строки. y вниз (как виджеты).
// Возвращает ширину px (для layout), 0 если не влезло/нет атласа.
float ui_text_quad(UiText *t, float x, float y, const char *s, const float rgba[4]);
// Нарисовать накопленное в текущую цель W×H (Y вниз -> ortho сам флипает).
void ui_text_flush(UiText *t, int w, int h);
unsigned ui_text_tex(const UiText *t);
// Ширина строки в px БЕЗ отрисовки (каретка/центрирование). Printable ASCII —
// как ui_text_quad; остальное — полширины (в атласе нет глифа).
float ui_text_width(UiText *t, const char *s);

// §14 F5k: НЕ ПИСАТЬ ТЕКСТ ПОД ЗАКРЫТОЙ ПОВЕРХНОСТЬЮ. Текст у нас отдельный
// проход, который рисуется ПОВЕРХ всех фигур: если панель-окно лежит на тексте
// (легаси-хром редактора пишет свой текст вслепую), он просвечивает сквозь окно.
// Задаём прямоугольники-перекрытия (например, открытые панели редактора) — квад,
// чей верх-лево попал внутрь, не рисуется. 0 прямоугольников = выключено.
#define UI_TEXT_MAXOCC 8
void ui_text_occluders(const float (*rects)[4], int n);
// Диагностика/тесты: сколько квадов набрано в кадре (бюджет = UI_TEXT_MAXQ).
// Нужно, чтобы «текст пропал» ловилось числом, а не глазами.
int ui_text_quads(const UiText *t);
// Тест/диагностика: точка перекрыта? (без атласа — чистая функция)
int ui_text_occluded(float x, float y);

#endif // ENGINE_UI_TEXT_H
