#ifndef UI_LOG_H
#define UI_LOG_H
// §14 Ш1c: КОНСОЛЬ РЕДАКТОРА — ДАННЫЕ. ОДНА реализация на всех, кто хочет писать
// в консоль (сегодня ui_edit; дальше — игровой редактор, импорт ассетов, скрипты).
// Данные отдельно от вида: панель-консоль — лишь ЧИТАТЕЛЬ этого кольца, поэтому
// вторая консоль (в игровом редакторе) не потребует второй реализации.
// Кольцо фиксированного размера: без malloc (правило кадра), старые строки
// вытесняются — как Output/Terminal в VS Code, где история ограничена.
#define UI_LOG_LINES 256 // сколько строк помним
#define UI_LOG_LINE 160  // сколько символов в строке (хвост усекаем)
void ui_log_clear(void);
void ui_log_add(const char *fmt, ...); // printf-стиль, '\n' в конце не нужен
int ui_log_n(void);                    // живых строк: 0..UI_LOG_LINES
const char *ui_log_line(int i);        // 0 = САМАЯ СТАРАЯ из живых
unsigned ui_log_total(void);           // сколько строк добавлено всего
#endif
